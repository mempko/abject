  private async createWindow(
    owner: AbjectId,
    title: string,
    rect: { x: number; y: number; width: number; height: number },
    options?: { chromeless?: boolean; resizable?: boolean; zIndex?: number }
  ): Promise<string> {
    require(this.uiServerId !== undefined, 'UIServer not set');

    const ownerTheme = this.getThemeForOwner(owner);
    const win = new WindowAbject({
      title,
      rect,
      uiServerId: this.uiServerId!,
      chromeless: options?.chromeless,
      resizable: options?.resizable,
      zIndex: options?.zIndex ?? 100,
      theme: ownerTheme,
      focusDecoration: this.focusDecoration,
    });

    await win.init(this.bus, this.id);
    this.spawnedWindows.add(win.id);

    // Tag the surface with the OWNER's workspace. Objects with no workspace
    // (global objects such as prompts and browsers) stay untagged so the
    // compositor shows them everywhere; objects in a background workspace stay
    // hidden until that workspace is active.
    const ownerWs = this.objectWorkspaces.get(owner);
    if (ownerWs && win.surface) {
      await this.request(request(this.id, this.uiServerId!, 'setSurfaceWorkspace', { surfaceId: win.surface, workspaceId: ownerWs }));
    }

    // Register as dependent of the window (for windowMoved/windowResized events)
    await this.request(
      request(this.id, win.id, 'addDependent', {})
    );

    // Register with WindowManager for z-order and drag/resize management
    if (this.windowManagerId && win.surface) {
      try {
        await this.request(request(this.id, this.windowManagerId,
          'registerWindow', {
            surfaceId: win.surface, windowId: win.id, zIndex: options?.zIndex ?? 100,
            rect, chromeless: options?.chromeless ?? false,
            draggable: false,
            title,
            titleBarHeight: ownerTheme.titleBarHeight,
            titleButtonSize: ownerTheme.titleButtonSize,
            titleButtonMargin: ownerTheme.titleButtonMargin,
            workspaceId: ownerWs,
          }));
      } catch { /* WindowManager may not be ready */ }
    }

    // Generate a shim window ID for backward compat
    const shimWindowId = `wm-win-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
    this.shimWindowMap.set(shimWindowId, win.id);
    this.windowOwners.set(win.id, owner);

    return shimWindowId;
  }

